// Helper function para obtener el contenido según el idioma
export interface LocalizedNewsItem {
  id: string;
  title: string;
  excerpt: string;
  category: string;
  date: string;
  author: string;
  source: string;
  content: string;
  image?: string;
}

export const getLocalizedNews = (language: 'es' | 'en'): LocalizedNewsItem[] => {
  return newsData.map(news => ({
    id: news.id,
    title: news.title[language],
    excerpt: news.excerpt[language],
    category: news.category[language],
    date: news.date,
    author: news.author,
    source: news.source,
    content: news.content[language],
    image: news.image
  }));
};

export const getLocalizedNewsById = (id: string, language: 'es' | 'en'): LocalizedNewsItem | undefined => {
  const news = newsData.find(item => item.id === id);
  if (!news) return undefined;
  
  return {
    id: news.id,
    title: news.title[language],
    excerpt: news.excerpt[language],
    category: news.category[language],
    date: news.date,
    author: news.author,
    source: news.source,
    content: news.content[language],
    image: news.image
  };
};